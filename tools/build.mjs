// Single-file build (decision P6): bundles src/ + vendored three.js into build/VoxelCity.html.
// Double-click that file to play — no server or install needed.
// Also writes build/index.html (same game — GitHub Pages opens index.html at the site link) and docs/CHANGELOG.md
// (from src/data/changelog.ts, the in-game patch notes).
// Usage: node tools/build.mjs   (uses esbuild from node_modules, or ESBUILD_PATH if set)
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
let esbuild;
try { esbuild = require(process.env.ESBUILD_PATH || 'esbuild'); }
catch { console.error('esbuild not found. Run `npm install` (or set ESBUILD_PATH).'); process.exit(1); }

const result = await esbuild.build({
  entryPoints: [resolve(root, 'src/main.ts')],
  bundle: true,
  format: 'iife',
  target: 'es2020',
  minify: true,
  write: false,
  alias: { three: resolve(root, 'vendor/three.module.js') },
  legalComments: 'none',
  logLevel: 'warning',
});
const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
// patch notes → version stamp + docs/CHANGELOG.md
const notes = await esbuild.build({ entryPoints: [resolve(root, 'src/data/changelog.ts')], bundle: true, format: 'esm', write: false, logLevel: 'warning' });
const { CHANGELOG, VERSION } = await import('data:text/javascript;base64,' + Buffer.from(notes.outputFiles[0].text).toString('base64'));
const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));
if (pkg.version !== VERSION) console.warn(`note: package.json says ${pkg.version} but the patch notes say ${VERSION} (the build uses ${VERSION})`);
const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Voxel City</title>
<!-- Voxel City V${VERSION} — built ${new Date().toISOString()} — three.js r170 (MIT) -->
</head>
<body>
<script>${js}</script>
</body>
</html>`;
mkdirSync(resolve(root, 'build'), { recursive: true });
writeFileSync(resolve(root, 'build/VoxelCity.html'), html);
writeFileSync(resolve(root, 'build/index.html'), html);
const KINDS = [['added', 'Added'], ['changed', 'Changed'], ['fixed', 'Fixed'], ['removed', 'Removed']];
const md = ['# Voxel City — patch notes', '', '_Generated by `tools/build.mjs` from `src/data/changelog.ts` (the in-game patch notes). Edit that file, not this one._', '',
  ...CHANGELOG.flatMap(v => [`## V${v.version} — ${v.title}`, `_${v.date}_`, '', ...KINDS.filter(([k]) => v[k]?.length).flatMap(([k, l]) => [`**${l}**`, ...v[k].map(t => `- ${t}`), '']), ''])].join('\n');
writeFileSync(resolve(root, 'docs/CHANGELOG.md'), md);
console.log(`build/VoxelCity.html + build/index.html  ${(html.length / 1024).toFixed(0)} KB · V${VERSION} · docs/CHANGELOG.md`);
