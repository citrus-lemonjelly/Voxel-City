/** Pixel cells for a string: [col, row] with row 0 at the top. Letters are 3 wide with a 1-cell gap. */
export function textCells(text: string): { cells: [number, number][]; width: number } {
  const cells: [number, number][] = [];
  let x = 0;
  for (const ch of text.toUpperCase()) {
    const g = F[ch] || F[' '];
    g.forEach((row, r) => [...row].forEach((b, c) => { if (b === '1') cells.push([x + c, r]); }));
    x += 4;
  }
  return { cells, width: Math.max(0, x - 1) };
}
