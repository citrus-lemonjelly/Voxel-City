// Single-file build (decision P6): bundles src/ + vendored three.js into build/VoxelCity.html.
// Double-click that file to play — no server or install needed.
// Also writes build/index.html (same game — GitHub Pages opens index.html at the site link), build/version.json (the live
// game checks it to announce updates) and docs/CHANGELOG.md
// (from src/data/changelog.ts, the in-game patch notes).
// Usage: node tools/build.mjs   (uses esbuild from node_modules, or ESBUILD_PATH if set)
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
let esbuild;
try { esbuild = require(process.env.ESBUILD_PATH || 'esbuild'); }
catch { console.error('esbuild not found. Run `npm install` (or set ESBUILD_PATH).'); process.exit(1); }

// patch notes → version stamp + docs/CHANGELOG.md
const notes = await esbuild.build({ entryPoints: [resolve(root, 'src/data/changelog.ts')], bundle: true, format: 'esm', write: false, logLevel: 'warning' });
const { CHANGELOG, VERSION } = await import('data:text/javascript;base64,' + Buffer.from(notes.outputFiles[0].text).toString('base64'));
const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));
if (pkg.version !== VERSION) console.warn(`note: package.json says ${pkg.version} but the patch notes say ${VERSION} (the build uses ${VERSION})`);
const BUILT = new Date().toISOString();
const result = await esbuild.build({
  entryPoints: [resolve(root, 'src/main.ts')],
  bundle: true,
  format: 'iife',
  target: 'es2020',
  minify: true,
  write: false,
  alias: { three: resolve(root, 'vendor/three.module.js') },
  legalComments: 'none',
  logLevel: 'warning',
  // stamped into the game: it compares itself with build/version.json on the site to announce updates (owner V0.2.1)
  define: { __VC_BUILD__: JSON.stringify({ version: VERSION, built: BUILT }) },
});
const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Voxel City</title>
<link rel="manifest" href="manifest.webmanifest">
<meta name="theme-color" content="#14161c">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<meta name="apple-mobile-web-app-title" content="Voxel City">
<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">
<link rel="icon" href="icons/icon-192.png">
<!-- Voxel City V${VERSION} — built ${BUILT} — three.js r170 (MIT) -->
</head>
<body>
<script>${js}</script>
</body>
</html>`;
mkdirSync(resolve(root, 'build'), { recursive: true });
writeFileSync(resolve(root, 'build/VoxelCity.html'), html);
writeFileSync(resolve(root, 'build/index.html'), html);
// "Add to home screen" (owner E3, V0.15.0): the app manifest + icons (assets/icons, made by tools/make-icons.mjs), so a phone
// opens the game full screen, sideways, with its own icon
mkdirSync(resolve(root, 'build/icons'), { recursive: true });
for (const f of readdirSync(resolve(root, 'assets/icons')).filter(f => f.endsWith('.png'))) copyFileSync(resolve(root, 'assets/icons', f), resolve(root, 'build/icons', f));
writeFileSync(resolve(root, 'build/manifest.webmanifest'), JSON.stringify({
  name: 'Voxel City', short_name: 'Voxel City', start_url: './', scope: './', display: 'fullscreen', orientation: 'landscape',
  background_color: '#14161c', theme_color: '#14161c',
  icons: [{ src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any maskable' }, { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any maskable' }],
}, null, 2) + '\n');
// what the live game checks to know a newer build is up (it reloads into it when the player says so)
writeFileSync(resolve(root, 'build/version.json'), JSON.stringify({ version: VERSION, built: BUILT, title: CHANGELOG[0].title }, null, 2) + '\n');
const KINDS = [['added', 'Added'], ['changed', 'Changed'], ['fixed', 'Fixed'], ['removed', 'Removed']];
const md = ['# Voxel City — patch notes', '', '_Generated by `tools/build.mjs` from `src/data/changelog.ts` (the in-game patch notes). Edit that file, not this one._', '',
  ...CHANGELOG.flatMap(v => [`## V${v.version} — ${v.title}`, `_${v.date}_`, '', ...KINDS.filter(([k]) => v[k]?.length).flatMap(([k, l]) => [`**${l}**`, ...v[k].map(t => `- ${t}`), '']), ''])].join('\n');
writeFileSync(resolve(root, 'docs/CHANGELOG.md'), md);
console.log(`build/VoxelCity.html + index.html + version.json + manifest + icons  ${(html.length / 1024).toFixed(0)} KB · V${VERSION} · docs/CHANGELOG.md`);
